import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, rm, readFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { randomBytes } from 'node:crypto';
import { encryptBytes, decryptBytes, wrapPassword, unwrapPassword, createRecoveryCode, wrapRecovery, unwrapRecovery } from '../lib/crypto/primitives';

test('key slots authenticate passwords, recovery codes and ciphertext/header integrity', async () => {
  const key = randomBytes(32), code = createRecoveryCode();
  const slot = await wrapPassword(key, 'correct-horse-battery');
  assert.deepEqual(await unwrapPassword(slot, 'correct-horse-battery'), key);
  await assert.rejects(unwrapPassword(slot, 'incorrect-password'));
  assert.deepEqual(unwrapRecovery(wrapRecovery(key, code), code), key);
  const aad = Buffer.from('header'), sealed = encryptBytes(Buffer.from('secret'), key, 'test', aad);
  assert.equal(decryptBytes(sealed, key, 'test', aad).toString(), 'secret');
  assert.throws(() => decryptBytes(sealed, key, 'test', Buffer.from('tampered')));
  sealed[sealed.length - 1] ^= 1;
  assert.throws(() => decryptBytes(sealed, key, 'test', aad));
});

test('filled SQLite, documents, access rotation and recovery survive encrypt/decrypt transitions', async () => {
  const dir = await mkdtemp(join(tmpdir(), 'tdb-vault-test-'));
  process.env.DATA_DIR = dir; process.env.DATABASE_URL = `file:${join(dir, 'data.db')}`;
  process.env.UPLOADS_DIR = join(dir, 'uploads'); process.env.AUTH_FILE = join(dir, 'auth.json'); process.env.APP_PASSWORD = '';
  const { createAdmin, createPrimary } = await import('../lib/auth/accounts');
  const { accountVersion } = await import('../lib/auth/authorization');
  const { readAuth } = await import('../lib/auth/store');
  const { prisma } = await import('../lib/db');
  const { readScanFile, writeScanFile } = await import('../lib/uploads');
  const { activeDatabasePath, uploadsDirectory } = await import('../lib/storage/paths');
  const { prepareEncryption, enableEncryption, disableEncryption, changePrimaryPassword } = await import('../lib/storage/access-management');
  const vault = await import('../lib/storage/vault');
  const { encodeVaultBundle, decodeVaultBundle } = await import('../lib/crypto/bundle');
  let stage = 'setup';
  try {
    await createAdmin('admin-password-long');
    const admin = (await readAuth()).admin!;
    await createPrimary({ authenticated: true, role: 'admin', userId: admin.id, authVersion: accountVersion(admin) }, 'operator', 'primary-password-long');
    const p = await prisma.person.create({ data: { lastName: 'Иванов', firstName: 'Пётр', birthDate: '1980-03-04', phone: '+7000123456' } });
    await writeScanFile(`${p.id}/doc.pdf`, Buffer.from('%PDF-1.4\npassport secret\n'));
    await prisma.passportScan.create({ data: { personId: p.id, filename: 'doc.pdf', storedPath: `${p.id}/doc.pdf`, mimeType: 'application/pdf', sizeBytes: 26 } });
    stage = 'prepare';
    const prepared = await prepareEncryption(admin.id, 'primary-password-long');
    await assert.rejects(enableEncryption(admin.id, 'primary-password-long', prepared.token, false));
    stage = 'enable';
    await enableEncryption(admin.id, 'primary-password-long', prepared.token, true);
    assert.equal(vault.vaultEncryptionEnabled(), true);
    await assert.rejects(prisma.person.findMany());
    assert.ok(!(await readFile(activeDatabasePath())).includes(Buffer.from('Иванов')));
    assert.equal((await readFile(join(uploadsDirectory(), p.id, 'doc.pdf'))).subarray(0, 5).toString(), 'TDBE1');
    await assert.rejects(vault.vaultUnlock('wrong-password'));
    await vault.vaultUnlock('primary-password-long');
    assert.equal((await prisma.person.findUniqueOrThrow({ where: { id: p.id } })).birthDate, '1980-03-04');
    const { searchPeople } = await import('../lib/search');
    assert.equal((await searchPeople('Иванов'))[0]?.id, p.id);
    await prisma.person.update({ where: { id: p.id }, data: { lastName: 'Иванова' } });
    assert.equal((await searchPeople('Иванова'))[0]?.id, p.id);
    assert.equal((await readScanFile(`${p.id}/doc.pdf`)).toString(), '%PDF-1.4\npassport secret\n');
    const bundle = await encodeVaultBundle(Buffer.from('private sync payload'));
    assert.ok(!bundle.includes(Buffer.from('private sync payload')));
    await assert.rejects(decodeVaultBundle(bundle, 'wrong-password'));
    assert.equal((await decodeVaultBundle(bundle, 'primary-password-long')).payload.toString(), 'private sync payload');
    const { buildExportZip } = await import('../lib/export');
    const { executeImport } = await import('../lib/import');
    const backup = await buildExportZip('full'), chunks: Buffer[] = [];
    for await (const chunk of backup.stream) chunks.push(Buffer.from(chunk));
    const protectedBackup = Buffer.concat(chunks);
    assert.ok(backup.filename.endsWith('.tdbbackup'));
    await assert.rejects(executeImport({ zipBuffer: protectedBackup, mode: 'merge', dryRun: true, password: 'wrong-password' }));
    const restorePlan = await executeImport({ zipBuffer: protectedBackup, mode: 'merge', dryRun: true, password: 'primary-password-long' });
    assert.ok('people' in restorePlan);
    assert.equal(restorePlan.people.toUpdate, 1);
    assert.equal(await prisma.person.count(), 1);
    stage = 'recover';
    const changed = await changePrimaryPassword(prepared.recoveryCode, 'new-primary-password', true);
    assert.ok(changed.recoveryCode && changed.recoveryCode !== prepared.recoveryCode);
    await assert.rejects(vault.vaultUnlock('primary-password-long'));
    await vault.vaultUnlock('new-primary-password');
    stage = 'disable';
    await disableEncryption(changed.recoveryCode!, true);
    assert.equal(vault.vaultEncryptionEnabled(), false);
    await vault.vaultUnlock('new-primary-password');
    assert.equal((await prisma.person.findUniqueOrThrow({ where: { id: p.id } })).phone, '+7000123456');
    assert.equal((await readScanFile(`${p.id}/doc.pdf`)).toString(), '%PDF-1.4\npassport secret\n');
    assert.equal(await prisma.changeOperation.count() >= 2, true);
  } catch (e) { if (e instanceof Response) throw new Error(`${stage}: ${JSON.stringify(await e.json())}`); throw e; }
  finally { await vault.vaultLock(); await prisma.$disconnect(); await rm(dir, { recursive: true, force: true }); }
});
